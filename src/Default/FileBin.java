    private void displayRecycleBinContents() {
    // JDBC connection parameters
     String url = "jdbc:mysql://localhost:3307/Kronosphere"; // Update URL with your database details
    String username = "root";
    String password = "kronosphereTSM";

    try (Connection connection = DriverManager.getConnection(url, username, password)) {
        // Query to retrieve data from recyclebin table
                createRecycleBinTable(connection);

        String sql = "SELECT file_name, file_path, deletion_date FROM recyclebin";
        
        try (Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(sql)) {

            // Create table model to store data for JTable
            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new Object[]{"File Name", "File Path", "Deletion Date"});

            // Loop through the result set and populate the table model
            while (resultSet.next()) {
                String fileName = resultSet.getString("file_name");
                String filePath = resultSet.getString("file_path");
                Timestamp deletionDate = resultSet.getTimestamp("deletion_date");

                // Add data to the table model
                model.addRow(new Object[]{fileName, filePath, deletionDate});
            }

            // Set the model to the jTable1
            FileBin.setModel(model);
        }
    } catch (SQLException e) {
        e.printStackTrace();
        // Handle database connection issues or SQL errors
    }
}
    private void createRecycleBinTable(Connection connection) throws SQLException {
    // SQL statement to create recyclebin table if it doesn't exist
    String createTableSQL = "CREATE TABLE IF NOT EXISTS recyclebin (id INT AUTO_INCREMENT PRIMARY KEY, file_name VARCHAR(255), file_path VARCHAR(1000), deletion_date TIMESTAMP)";

    try (Statement statement = connection.createStatement()) {
        // Execute the SQL statement to create the table
        statement.execute(createTableSQL);
    }
}
    private void startAutoRefresh() {
        int refreshInterval = 7000; // Refresh interval in milliseconds (e.g., every 7 seconds)
        Timer timer = new Timer(refreshInterval, e -> {
            displayRecycleBinContents(); // Refresh table contents
        });
        timer.start();
    }
   // Method to remove the file entry from the Recycle Bin database
private void removeFromRecycleBinDatabase(String fileName) {
     String url = "jdbc:mysql://localhost:3307/Kronosphere"; // Update URL with your database details
    String username = "root";
    String password = "kronosphereTSM";

    try (Connection connection = DriverManager.getConnection(url, username, password)) {
        Statement statement = connection.createStatement();

        // Execute a SQL DELETE query to remove the file entry
        String deleteQuery = "DELETE FROM recyclebin WHERE file_name = '" + fileName + "'";
        statement.executeUpdate(deleteQuery);

        System.out.println("File removed from Recycle Bin database.");
        
        // Close resources
        statement.close();
        connection.close();
    } catch (SQLException ex) {
        System.err.println("Error removing file from Recycle Bin database: " + ex.getMessage());
    }
}

