    private void RestoreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RestoreActionPerformed
    int selectedRow = FileBin.getSelectedRow(); // Get the index of the selected row in the Recycle Bin table

        if (selectedRow != -1) { // Ensure a row is selected in the Recycle Bin table
            String fileName = (String) FileBin.getValueAt(selectedRow, 0); // Assuming file name is in the first column

            // Get the project directory path
            String projectDirectory = System.getProperty("user.dir");

            // Create a directory for restored files within the Kronosphere folder in the project directory
            String kronospherePath = projectDirectory + "/Kronosphere";
            String restoredInKronospherePath = kronospherePath + "/Restored Files";

            // Create the "Restored Files" directory if it doesn't exist within the Kronosphere folder
            File restoredInKronosphereDirectory = new File(restoredInKronospherePath);
            if (!restoredInKronosphereDirectory.exists()) {
                boolean created = restoredInKronosphereDirectory.mkdirs();
                if (!created) {
                    System.err.println("Failed to create Restored Files folder in Kronosphere.");
                    return;
                }
            }

            // Get the path to the file in the Recycle Bin within the Kronosphere folder
            String recycleBinPath = kronospherePath + "/Recycle Bin";
            File fileInRecycleBin = new File(recycleBinPath + "/" + fileName);

            // Move the file from Recycle Bin to the "Restored Files" in Kronosphere
            File restoredFileLocation = new File(restoredInKronospherePath + "/" + fileName);

            try {
                Files.move(fileInRecycleBin.toPath(), restoredFileLocation.toPath(), StandardCopyOption.REPLACE_EXISTING);
                System.out.println("File restored successfully.");

                // Remove the file from the Recycle Bin database
                removeFromRecycleBinDatabase(fileName);
            } catch (IOException ex) {
                System.err.println("Error restoring file: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_RestoreActionPerformed

    private void Shred1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Shred1ActionPerformed
          int selectedRow = FileBin.getSelectedRow(); // Get the index of the selected row in the Recycle Bin table

    if (selectedRow != -1) { // Ensure a row is selected in the Recycle Bin table
        String fileName = (String) FileBin.getValueAt(selectedRow, 0); // Assuming file name is in the first column

        String projectDirectory = System.getProperty("user.dir");
        String kronospherePath = projectDirectory + "/Kronosphere";

        // Create a path to the Recycle Bin folder inside Kronosphere
        String recycleBinPath = kronospherePath + "/Recycle Bin";
        String filePathInRecycleBin = recycleBinPath + "/" + fileName;

        // Create a File object for the file in the Recycle Bin
        File fileToDelete = new File(filePathInRecycleBin);

        try {
            // Permanently delete the file
            Files.deleteIfExists(fileToDelete.toPath());
            System.out.println("File permanently shredded.");

            // Remove the file from the Recycle Bin database
            removeFromRecycleBinDatabase(fileName); // Assuming this method removes the file from the database

            // Update the table after shredding (remove the row)
            DefaultTableModel model = (DefaultTableModel) FileBin.getModel();
            model.removeRow(selectedRow);

            // Show a dialog confirming successful file shredding
            JOptionPane.showMessageDialog(null, "File permanently shredded.", "File Shredded", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException ex) {
            System.err.println("Error shredding file: " + ex.getMessage());
        }
    } else {
        System.out.println("Please select a file to shred from the Recycle Bin.");
    }
    }//GEN-LAST:event_Shred1ActionPerformed


